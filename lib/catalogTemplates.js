export function getResolvedProductImage(prod, liveProducts = [], customOverrides = {}) {
  if (!prod) return null;
  const prodId = prod.id || prod.sku;
  
  // 1. Cek dari overrides admin
  if (prodId && customOverrides[prodId]?.image) {
    return customOverrides[prodId].image;
  }
  
  // 2. Cek jika produk sudah punya gambar spesifik
  if (prod.image && prod.image.trim()) return prod.image;
  if (prod.img && prod.img.trim()) return prod.img;

  const nameLower = ((prod.name || '') + ' ' + (prod.brand || '')).toLowerCase();

  // 3. Cek dari liveProducts database yang memiliki gambar
  if (liveProducts && liveProducts.length > 0) {
    const dbMatch = liveProducts.find((p) => {
      if (!p.image) return false;
      const pName = (p.name || '').toLowerCase();
      const pBrand = (p.brand || '').toLowerCase();
      return (pBrand && nameLower.includes(pBrand)) || 
             (pName && (nameLower.includes(pName.slice(0, 8)) || pName.includes(nameLower.slice(0, 8))));
    });
    if (dbMatch?.image) return dbMatch.image;
  }

  // 4. Cek dari dictionary template warna D Store
  for (const [key, pth] of Object.entries(CATALOG_TEMPLATE_MAP)) {
    if (nameLower.includes(key)) return pth;
  }

  return '/uploads/desain_tanpa_judul__4_-1791989747452.webp';
}

export function buildUnifiedCatalog({ liveProducts = [], liveVariants = [], categoryOverrides = {} }) {
  const combined = [];
  const seenKeys = new Set();

  // 1. Tambahkan semua produk dari database liveProducts
  for (const p of liveProducts) {
    const id = p.id || p.sku;
    const key = ((p.brand || '') + ' ' + (p.name || '')).toLowerCase().trim();
    if (seenKeys.has(key)) continue;
    seenKeys.add(key);

    const ov = categoryOverrides[id] || {};
    const finalImage = ov.image || p.image || getResolvedProductImage(p, liveProducts, categoryOverrides);
    const finalName = ov.name || p.name;
    const finalBrand = (ov.brand || p.brand || p.name || 'D STORE').toUpperCase();

    // Hitung varian & harga terendah
    const vars = (liveVariants || []).filter((v) => v.productId === id);
    const validPrices = vars.map((v) => Number(v.price) || 0).filter((pr) => pr > 0);
    const minPrice = validPrices.length > 0 ? Math.min(...validPrices) : (Number(ov.price || p.price) || 15000);
    const anyAvailable = vars.length > 0 ? vars.some((v) => v.isAvailable !== false) : true;

    const catName = CATEGORY_NAMES_MAP[p.categoryId] || p.category || 'Aplikasi Premium';
    const catSlug = CATEGORY_SLUGS_MAP[p.categoryId] || 'all';

    combined.push({
      id,
      sku: id,
      name: finalName,
      brand: finalBrand,
      categoryId: p.categoryId || 'cat_1',
      categoryName: catName,
      categorySlug: catSlug,
      description: p.description || `${finalBrand} Akun Premium Resmi & Bergaransi D Store`,
      image: finalImage,
      price: minPrice,
      priceNumber: minPrice,
      originalPriceNumber: Math.round(minPrice * 1.5),
      discount: '-33%',
      isAvailable: anyAvailable,
      variantsCount: vars.length,
      isDatabaseItem: true
    });
  }

  // 2. Tambahkan curated apps utama (seperti Gemini, dll) jika belum ada di list
  const CURATED_FLAGSHIPS = [
    {
      id: 'curated_gemini',
      sku: 'curated_gemini',
      name: 'Gemini Advanced 1.5 Pro & Imagen 3 Google AI',
      brand: 'GEMINI',
      categoryId: 'cat_1',
      categoryName: 'AI & Tools',
      categorySlug: 'ai-tools',
      description: 'Akses Gemini Advanced dengan integrasi Google Workspace & Imagen 3.',
      image: '/uploads/desain_tanpa_judul__4_-1791989747452.webp',
      price: 15000,
      priceNumber: 15000,
      originalPriceNumber: 30000,
      discount: '-50%',
      isAvailable: true,
      variantsCount: 3
    }
  ];

  for (const c of CURATED_FLAGSHIPS) {
    const key = ((c.brand || '') + ' ' + (c.name || '')).toLowerCase().trim();
    if (!seenKeys.has(key)) {
      seenKeys.add(key);
      combined.push(c);
    }
  }

  return combined;
}

export function searchCatalog(catalog, query) {
  if (!query || !query.trim()) return [];
  const q = query.toLowerCase().trim();
  
  // Jika hanya 1 huruf, hanya cocokkan dengan awalan Brand atau Nama (misal 'c' -> Canva, CapCut)
  if (q.length < 2) {
    return catalog.filter((item) => {
      const brandLower = (item.brand || '').toLowerCase();
      const nameLower = (item.name || '').toLowerCase();
      return brandLower.startsWith(q) || nameLower.startsWith(q);
    });
  }

  const qTerms = q.split(/\s+/).filter(Boolean);
  const scored = [];

  for (const item of catalog) {
    const nameLower = (item.name || '').toLowerCase();
    const brandLower = (item.brand || '').toLowerCase();
    const catLower = (item.categoryName || '').toLowerCase();
    const cleanDesc = (item.description || '').toLowerCase()
      .replace(/akun|resmi|bergaransi|premium|d store|lifetime/g, '');
    const combinedText = `${brandLower} ${nameLower} ${catLower} ${cleanDesc}`;

    let score = 0;

    // Exact matches
    if (brandLower === q) score += 200;
    else if (brandLower.startsWith(q)) score += 120;
    else if (brandLower.includes(q)) score += 80;

    if (nameLower.startsWith(q)) score += 100;
    else if (nameLower.includes(q)) score += 60;

    if (catLower.includes(q)) score += 40;

    // Multi-term matching
    const matchesAllTerms = qTerms.every(term => combinedText.includes(term));
    if (matchesAllTerms) {
      score += 50 * qTerms.length;
    } else {
      const anyTermMatches = qTerms.some(term => brandLower.includes(term) || nameLower.includes(term) || catLower.includes(term));
      if (!anyTermMatches && score === 0) continue;
      score += 15;
    }

    if (score > 0) {
      scored.push({ item, score });
    }
  }

  scored.sort((a, b) => b.score - a.score);
  return scored.map(s => s.item);
}
